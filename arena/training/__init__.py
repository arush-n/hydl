"""Reusable JAX training techniques over Arena policies and rollouts.

This package supplies tunable machinery, not tuned policies. Each subpackage
holds one kind of thing; its own ``__init__`` docstring names the modules
inside.

``contracts``
    Complete lessons -- a reward law, the action heads it trains, and a
    content-addressed manifest. This is what a policy is paid to do.
``rewards``
    Reward streams that compose into a lesson but are not lessons themselves:
    combat shaping, behaviour priors, exact-imitation alignment, RND/RIDE/GAIL.
``imitation``
    Behaviour cloning and the native-trace pipeline that feeds it.
``skills``
    Skill-stage machinery: ``FactoredActionScope``, causal signals, resets.
``algorithms``
    Learners and optimisers: recurrent PPO, evolution, auto-improvement.
``diagnostics``
    Measurement only. Nothing here changes a policy.
``runs``
    Executable ``python -m`` entrypoints.
``runtime``
    Versioned *training-run* contracts -- metrics, stop-loss, feature programs.
    Distinct from ``contracts``, which is about the reward law.
``selfplay``
    League snapshots and live two-policy duels.

The names below are re-exported so ``from arena.training import X`` keeps
working across the subpackage split. Import the full path when you want to be
explicit about which layer you are reaching into. See ``DEV.md`` for the
layout table and the two name collisions worth knowing about.
"""

