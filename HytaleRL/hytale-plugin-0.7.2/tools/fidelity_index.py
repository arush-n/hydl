#!/usr/bin/env python3
"""Regenerate the table of contents of FIDELITY-0.7.2.md between its index markers.

One line per "## (x) ..." section: the letter, the title (the text before a "(2026" date note), the line number in
the file and, for a section with a table that has a Status column, the number of rows whose status cell starts with
OPEN, PENDING, NOT MET or UNMEASURED. The markers are inserted after the opening paragraph on the first run.
Run it after adding a section or editing one: line numbers move with every edit above them. Stdlib only.
"""

from __future__ import annotations

import re
from pathlib import Path

PLUGIN = Path(__file__).resolve().parents[1]
FIDELITY = PLUGIN / "FIDELITY-0.7.2.md"
START = "<!-- fidelity-index-start -->"
END = "<!-- fidelity-index-end -->"
HEADER = re.compile(r"^## \(([a-z]+)\) (.+)$")
SEPARATOR = re.compile(r"\|?\s*:?-{3,}:?\s*(?:\|\s*:?-{3,}:?\s*)*\|?")
OPEN_WORDS = ("OPEN", "PENDING", "NOT MET", "UNMEASURED")
DESCRIPTION = ("Generated by tools/fidelity_index.py; do not edit by hand. Open rows: rows of a table with a Status "
               "column whose status starts with OPEN, PENDING, NOT MET or UNMEASURED.")


def _cells(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def _open_rows(lines: list[str]) -> tuple[bool, int]:
    """(the section has a table with a Status column, its rows whose status starts with an open word)."""
    has_status, open_rows = False, 0
    for i in range(len(lines) - 1):
        if not (lines[i].lstrip().startswith("|") and SEPARATOR.fullmatch(lines[i + 1].strip())):
            continue
        header = _cells(lines[i])
        column = next((n for n, name in enumerate(header) if name.lower() == "status"), None)
        if column is None:
            continue
        has_status = True
        for row in lines[i + 2:]:
            if not row.lstrip().startswith("|"):
                break
            cells = _cells(row)
            status = re.sub(r"[*`_]", "", cells[column]).strip().upper() if column < len(cells) else ""
            open_rows += status.startswith(OPEN_WORDS)
    return has_status, open_rows


def _sections(lines: list[str]) -> list[tuple[str, str, int, int]]:
    """(letter, title, header index, end index) for each lettered section; a section ends at the next "## "."""
    starts = [i for i, line in enumerate(lines) if line.startswith("## ")]
    found = []
    for n, i in enumerate(starts):
        match = HEADER.match(lines[i])
        if match:
            end = starts[n + 1] if n + 1 < len(starts) else len(lines)
            found.append((match.group(1), match.group(2).split(" (2026")[0].strip(), i, end))
    return found


def _strip_block(lines: list[str]) -> list[str]:
    if START not in lines:
        return lines
    first, last = lines.index(START), lines.index(END)
    cut = first - 1 if first > 0 and lines[first - 1] == "" else first
    return lines[:cut] + lines[last + 1:]


def _anchor(lines: list[str]) -> int:
    """Index of the blank line that ends the opening paragraph (after the H1)."""
    i = 1
    while i < len(lines) and not lines[i].strip():
        i += 1
    while i < len(lines) and lines[i].strip():
        i += 1
    return i


def render(text: str) -> str:
    lines = _strip_block(text.split("\n"))
    sections, anchor = _sections(lines), _anchor(lines)
    block_length = len(["", START, DESCRIPTION, "", *(["x"] * len(sections)), END])
    entries = []
    for letter, title, header, end in sections:
        number = header + 1 + (block_length if header >= anchor else 0)
        has_status, open_rows = _open_rows(lines[header:end])
        tail = f"; open rows {open_rows}" if has_status else ""
        entries.append(f"- ({letter}) {title}: line {number}{tail}")
    block = ["", START, DESCRIPTION, "", *entries, END]
    return "\n".join(lines[:anchor] + block + lines[anchor:])


def main() -> int:
    text = FIDELITY.read_text(encoding="utf-8")
    new = render(text)
    if new != text:
        FIDELITY.write_text(new, encoding="utf-8")
    listing = new.split(START, 1)[1].split(END, 1)[0].strip("\n")
    print(f"{FIDELITY.name}: index {'written' if new != text else 'unchanged'}")
    print(listing.split("\n", 1)[1].split("\n", 1)[1])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
