def __getattr__(name):
    """Load env-dependent adapters only after the combat package is ready."""

    if name in _RUNTIME_EXPORTS:
        module_name = "hytalegym.jax.combat.observation.v1.runtime.transition"
    elif name in _RUNTIME_V2_EXPORTS:
        module_name = "hytalegym.jax.combat.observation.v2.runtime"
    elif name in _V3_EXPORTS:
        module_name = "hytalegym.jax.combat.observation.v3"
    else:
        raise AttributeError(name)
    value = getattr(import_module(module_name), name)
    globals()[name] = value
    return value

